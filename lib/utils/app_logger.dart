import 'package:flutter/foundation.dart';

/// Диагностический вывод приложения.
///
/// Заменяет `print` в рантайм-коде по двум причинам:
///  * `print` запрещён линтом `avoid_print`;
///  * `print` и `debugPrint` пишут в консоль и в release-сборке, а часть
///    сообщений содержит тела ответов сервера и детали обновления токена —
///    в проде это попадает в системный лог устройства.
///
/// Здесь вывод обрезан по `kDebugMode`, поэтому в release не остаётся ничего.
/// `debugPrint` выбран вместо `print` ещё и потому, что он троттлит вывод и не
/// теряет строки при большом объёме логов.
void logDebug(String message) {
  if (kDebugMode) {
    debugPrint(message);
  }
}
